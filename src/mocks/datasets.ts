import type { DatasetLabelClass, DatasetRecord } from '../features/datasets/dataset.types';

const buildIndexedHeadings = (prefix: string, count: number, start = 0) =>
  Array.from({ length: count }, (_, index) => `${prefix}_${index + start}`);

const buildWindFarmVariableHeadings = ({
  sensor,
  windSpeed,
  reactivePower,
  power,
}: {
  sensor: number;
  windSpeed: number;
  reactivePower: number;
  power: number;
}) => [
  ...buildIndexedHeadings('sensor', sensor, 0),
  ...buildIndexedHeadings('wind_speed', windSpeed, sensor),
  ...buildIndexedHeadings('reactive_power', reactivePower, sensor + windSpeed),
  ...buildIndexedHeadings('power', power, sensor + windSpeed + reactivePower),
];

const buildLabelClasses = (entries: Array<[string, number]>): DatasetLabelClass[] =>
  entries.map(([name, count]) => ({ name, count }));

